class Camera(Base):
    """
    Camera/CCTV device metadata and configuration.

    Represents a physical camera deployed at border outposts.
    """

    __tablename__ = "cameras"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    uuid: Mapped[str] = mapped_column(
        PG_UUID(as_uuid=False),
        unique=True,
        nullable=False,
        index=True,
        comment="Universally unique identifier for edge device",
    )

    # Identification
    name: Mapped[str] = mapped_column(String(100), nullable=False, index=True)
    description: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    serial_number: Mapped[Optional[str]] = mapped_column(String(50), unique=True, nullable=True)

    # Network
    rtsp_url: Mapped[str] = mapped_column(String(500), nullable=False)
    ip_address: Mapped[Optional[str]] = mapped_column(String(45), nullable=True)
    mac_address: Mapped[Optional[str]] = mapped_column(String(17), nullable=True)

    # Location (WGS84)
    latitude: Mapped[float] = mapped_column(nullable=False, comment="GPS latitude in decimal degrees")
    longitude: Mapped[float] = mapped_column(nullable=False, comment="GPS longitude in decimal degrees")
    altitude: Mapped[Optional[float]] = mapped_column(nullable=True, comment="Altitude in meters")
    heading: Mapped[Optional[float]] = mapped_column(nullable=True, comment="Camera heading in degrees (0-360)")
    tilt: Mapped[Optional[float]] = mapped_column(nullable=True, comment="Camera tilt in degrees")
    fov_horizontal: Mapped[Optional[float]] = mapped_column(nullable=True, comment="Horizontal field of view")
    fov_vertical: Mapped[Optional[float]] = mapped_column(nullable=True, comment="Vertical field of view")

    # Operational
    status: Mapped[CameraStatus] = mapped_column(
        Enum(CameraStatus, native_enum=False),
        default=CameraStatus.OFFLINE,
        nullable=False,
        index=True,
    )
    health_score: Mapped[int] = mapped_column(Integer, default=100, nullable=False)
    last_heartbeat: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    last_frame_timestamp: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)

    # Configuration
    resolution_width: Mapped[int] = mapped_column(Integer, default=1920)
    resolution_height: Mapped[int] = mapped_column(Integer, default=1080)
    fps: Mapped[float] = mapped_column(default=30.0)
    codec: Mapped[str] = mapped_column(String(20), default="H264")
    bitrate_kbps: Mapped[int] = mapped_column(Integer, default=4096)

    # Analytics config (JSON)
    analytics_config: Mapped[dict[str, Any]] = mapped_column(
        JSON,
        default=lambda: {},
        nullable=False,
        comment="Per-camera analytics configuration",
    )

    # Encryption
    encryption_key_id: Mapped[Optional[str]] = mapped_column(String(64), nullable=True)

    # Timestamps
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )
    deployed_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    decommissioned_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)

    # Relationships
    alerts: Mapped[list["Alert"]] = relationship(
        "Alert",
        back_populates="camera",
        cascade="all, delete-orphan",
        lazy="dynamic",
    )
    audit_logs: Mapped[list["AuditLedger"]] = relationship(
        "AuditLedger",
        back_populates="camera",
        cascade="all, delete-orphan",
        lazy="dynamic",
    )

    __table_args__ = (
        Index("ix_cameras_location", "latitude", "longitude"),
        Index("ix_cameras_status_heartbeat", "status", "last_heartbeat"),
    )

    def to_dict(self) -> dict[str, Any]:
        """Convert to dictionary with datetime serialization."""
        data = super().to_dict()
        for key, value in data.items():
            if isinstance(value, datetime):
                data[key] = value.isoformat()
            elif isinstance(value, enum.Enum):
                data[key] = value.value
        return data


