class AuditLedger(Base):
    """
    Tamper-evident audit ledger using SHA-256 chaining.

    Each block contains a hash of the previous block, creating an immutable chain.
    """

    __tablename__ = "audit_ledger"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    uuid: Mapped[str] = mapped_column(
        PG_UUID(as_uuid=False),
        unique=True,
        nullable=False,
        index=True,
    )

    # Block chain
    block_index: Mapped[int] = mapped_column(Integer, nullable=False, unique=True, index=True)
    previous_hash: Mapped[str] = mapped_column(String(64), nullable=False)
    current_hash: Mapped[str] = mapped_column(String(64), nullable=False, unique=True)

    # References
    camera_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("cameras.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    alert_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("alerts.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    # Event data
    event_type: Mapped[str] = mapped_column(String(100), nullable=False, index=True)
    event_category: Mapped[str] = mapped_column(String(50), nullable=False, index=True)
    event_data: Mapped[dict[str, Any]] = mapped_column(JSON, nullable=False)

    # Cryptographic
    hash_algorithm: Mapped[str] = mapped_column(String(20), default="SHA256", nullable=False)
    signature: Mapped[Optional[str]] = mapped_column(String(256), nullable=True)
    public_key_id: Mapped[Optional[str]] = mapped_column(String(64), nullable=True)

    # Timestamp
    timestamp: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
        index=True,
    )

    # Relationships
    camera: Mapped[Optional["Camera"]] = relationship("Camera", back_populates="audit_logs")
    alert: Mapped[Optional["Alert"]] = relationship("Alert", back_populates="audit_logs")

    __table_args__ = (
        Index("ix_audit_camera_time", "camera_id", "timestamp"),
        Index("ix_audit_alert_time", "alert_id", "timestamp"),
        Index("ix_audit_block_chain", "block_index", "previous_hash"),
        UniqueConstraint("uuid", name="uq_audit_uuid"),
        UniqueConstraint("current_hash", name="uq_audit_current_hash"),
    )

    @staticmethod
    def compute_hash(
        block_index: int,
        previous_hash: str,
        event_type: str,
        event_category: str,
        event_data: dict[str, Any],
        timestamp: datetime,
    ) -> str:
        """
        Compute SHA-256 hash for a ledger block.

        Args:
            block_index: Sequential block number.
            previous_hash: Hash of previous block.
            event_type: Type of event.
            event_category: Category of event.
            event_data: Event payload.
            timestamp: Block timestamp.

        Returns:
            Hex-encoded SHA-256 hash.
        """
        # Deterministic serialization
        data = {
            "index": block_index,
            "prev": previous_hash,
            "type": event_type,
            "category": event_category,
            "data": event_data,
            "ts": timestamp.isoformat() if isinstance(timestamp, datetime) else timestamp,
        }
        serialized = json.dumps(data, separators=(",", ":"), sort_keys=True).encode("utf-8")
        return hashlib.sha256(serialized).hexdigest()

    def verify_chain(self, previous_block: Optional["AuditLedger"] = None) -> bool:
        """
        Verify this block's hash and chain integrity.

        Args:
            previous_block: Previous block in chain (optional).

        Returns:
            True if valid.
        """
        # Verify current hash
        expected = self.compute_hash(
            self.block_index,
            self.previous_hash,
            self.event_type,
            self.event_category,
            self.event_data,
            self.timestamp,
        )
        if expected != self.current_hash:
            return False

        # Verify chain link
        if previous_block:
            if self.previous_hash != previous_block.current_hash:
                return False
            if self.block_index != previous_block.block_index + 1:
                return False

        return True

    def to_dict(self) -> dict[str, Any]:
        """Convert to dictionary with datetime serialization."""
        data = super().to_dict()
        for key, value in data.items():
            if isinstance(value, datetime):
                data[key] = value.isoformat()
            elif isinstance(value, enum.Enum):
                data[key] = value.value
        return data


@dataclass(frozen=True, slots=True)
class LedgerBlock:
    """
    In-memory representation of a ledger block for building chain.

    Used by the ledger service before persisting.
    """

    block_index: int
    previous_hash: str
    event_type: str
    event_category: str
    event_data: dict[str, Any]
    timestamp: datetime
    camera_id: Optional[int] = None
    alert_id: Optional[int] = None
    hash_algorithm: str = "SHA256"
    signature: Optional[str] = None
    public_key_id: Optional[str] = None

    def compute_hash(self) -> str:
        """Compute block hash."""
        return AuditLedger.compute_hash(
            self.block_index,
            self.previous_hash,
            self.event_type,
            self.event_category,
            self.event_data,
            self.timestamp,
        )

    def to_orm(self) -> AuditLedger:
        """Convert to ORM model."""
        current_hash = self.compute_hash()
        return AuditLedger(
            uuid=f"{current_hash[:8]}-{int(time.time() * 1000)}",
            block_index=self.block_index,
            previous_hash=self.previous_hash,
            current_hash=current_hash,
            camera_id=self.camera_id,
            alert_id=self.alert_id,
            event_type=self.event_type,
            event_category=self.event_category,
            event_data=self.event_data,
            hash_algorithm=self.hash_algorithm,
            signature=self.signature,
            public_key_id=self.public_key_id,
            timestamp=self.timestamp,
        )


